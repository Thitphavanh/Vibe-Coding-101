class Command(BaseCommand):
    help = "เพิ่มข้อมูลบทความตัวอย่างเกี่ยวกับ AI"

    def add_arguments(self, parser):
        parser.add_argument(
            "--count",
            type=int,
            default=12,
            help="จำนวนบทความที่จะสร้าง (ค่าเริ่มต้น 12)",
        )
        parser.add_argument(
            "--clear",
            action="store_true",
            help="ลบ Post และ Category เดิมทั้งหมดก่อนสร้างข้อมูลใหม่",
        )
        parser.add_argument(
            "--author",
            type=str,
            default="admin",
            help="username ของผู้เขียนบทความ (ค่าเริ่มต้น admin)",
        )

    def handle(self, *args, **options):
        count = options["count"]
        clear = options["clear"]
        author_username = options["author"]

        User = get_user_model()
        author = User.objects.filter(username=author_username).first()
        if not author:
            raise CommandError(
                f"ไม่พบ user ชื่อ '{author_username}' กรุณาสร้าง superuser ก่อนด้วยคำสั่ง: "
                f"python manage.py createsuperuser"
            )

        posts_data = _get_posts_data()
        if count > len(posts_data):
            self.stdout.write(
                self.style.WARNING(
                    f"มีข้อมูลบทความที่เตรียมไว้เพียง {len(posts_data)} เรื่อง "
                    f"จะสร้างให้ {len(posts_data)} เรื่องแทนค่า --count={count} ที่ขอมา"
                )
            )
            count = len(posts_data)
        elif count < len(posts_data):
            posts_data = posts_data[:count]

        with transaction.atomic():
            if clear:
                deleted_posts = Post.objects.all().delete()[0]
                deleted_categories = Category.objects.all().delete()[0]
                self.stdout.write(
                    self.style.WARNING(
                        f"ลบข้อมูลเดิมแล้ว: Post {deleted_posts} รายการ, Category {deleted_categories} รายการ"
                    )
                )

            categories = {}
            for name in CATEGORY_NAMES:
                category, created = Category.objects.get_or_create(name=name)
                categories[name] = category
                if created:
                    self.stdout.write(self.style.SUCCESS(f"สร้างหมวดหมู่ใหม่: {category.name}"))
                else:
                    self.stdout.write(self.style.WARNING(f"หมวดหมู่มีอยู่แล้ว: {category.name}"))

            published_days_ago = random.sample(range(1, 91), len(posts_data))

            for index, post_data in enumerate(posts_data):
                related_categories = [categories[name] for name in post_data["categories"]]
                chosen_category = random.choice(related_categories)

                days_ago = published_days_ago[index]
                published_at = timezone.now() - timedelta(
                    days=days_ago,
                    hours=random.randint(0, 23),
                    minutes=random.randint(0, 59),
                )

                post, created = Post.objects.get_or_create(
                    title=post_data["title"],
                    defaults={
                        "author": author,
                        "content": post_data["content"],
                        "summary": post_data["summary"],
                        "category": chosen_category,
                        "status": "published",
                        "published_at": published_at,
                        "is_featured": index < 3,
                        "views": random.randint(50, 2000),
                    },
                )

                if created:
                    self.stdout.write(self.style.SUCCESS(f"สร้างบทความ: {post.title}"))
                else:
                    self.stdout.write(self.style.WARNING(f"บทความมีอยู่แล้ว ข้ามไป: {post.title}"))

        self.stdout.write(self.style.SUCCESS(f"เสร็จสิ้น! ประมวลผลบทความทั้งหมด {len(posts_data)} เรื่อง"))
